export type Strings = typeof fr

const STRINGS = { fr, sv, en, nl, es, de } satisfies Partial<Record<Lang, Strings>>

export type InterfaceLang = keyof typeof STRINGS

// Languages the interface can be read in, in display order
export const INTERFACE_LANGS = Object.keys(STRINGS) as InterfaceLang[]

export function getStrings(lang: string | null | undefined): Strings {
  return STRINGS[asLang(lang)]
}

export function asLang(value: string | null | undefined): InterfaceLang {
  return value && value in STRINGS ? (value as InterfaceLang) : (DEFAULT_LANG as InterfaceLang)
}
